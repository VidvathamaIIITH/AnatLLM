"""Run the full ablation (C1-C5) and aggregate the results.

Each configuration is launched in a **separate process** so that
``torch.cuda.max_memory_allocated`` measures that model alone -- otherwise C1's
peak would leak into C5's number and the memory comparison would be meaningless.

Usage::

    python -m src.run_all --data-dir data --epochs 15
    python -m src.run_all --configs C1,C5 --data-dir data --epochs 15
    python -m src.run_all --smoke --wandb disabled            # 2-minute sanity check

Any flag this script does not recognise is forwarded verbatim to ``src.train``.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from typing import Dict, List, Optional, Sequence

if __package__ in (None, ""):  # allow `python src/run_all.py`
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    __package__ = "src"

from .configs import CONFIGS  # noqa: E402
from .utils import (  # noqa: E402
    load_json,
    plot_ablation_bars,
    plot_efficiency,
    results_markdown_table,
    save_json,
)

MAIN_METRICS = [
    ("bit_accuracy", "Bit Acc (%)"),
    ("sequence_accuracy", "Seq Acc (%)"),
    ("levenshtein", "Levenshtein"),
    ("bleu", "BLEU"),
    ("rougeL", "ROUGE-L"),
]
EFFICIENCY_METRICS = [
    ("params_millions", "Params (M)"),
    ("sec_per_epoch", "s / epoch"),
    ("train_tokens_per_sec", "train tok/s"),
    ("peak_gpu_mem_mb", "Peak GPU MB"),
    ("generation_seconds", "Greedy decode (s)"),
]


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(
        description="Run every ablation configuration and aggregate the results"
    )
    ap.add_argument("--configs", default="C1,C2,C3,C4,C5")
    ap.add_argument("--out-dir", default="outputs")
    ap.add_argument("--python", default=sys.executable)
    ap.add_argument("--skip-existing", action="store_true",
                    help="skip a config whose metrics.json already exists")
    ap.add_argument("--aggregate-only", action="store_true",
                    help="do not train; just rebuild tables/plots from metrics.json")
    args, passthrough = ap.parse_known_args(argv)

    names = [c.strip().upper() for c in args.configs.split(",") if c.strip()]
    for n in names:
        if n not in CONFIGS:
            raise SystemExit(f"Unknown config '{n}'. Choose from {sorted(CONFIGS)}")

    os.makedirs(args.out_dir, exist_ok=True)
    repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

    # ------------------------------------------------------------------ train
    if not args.aggregate_only:
        for name in names:
            metrics_path = os.path.join(args.out_dir, name, "metrics.json")
            if args.skip_existing and os.path.exists(metrics_path):
                print(f"\n### {name}: metrics.json exists -> skipped\n", flush=True)
                continue
            cmd = [args.python, "-m", "src.train", "--config", name,
                   "--out-dir", args.out_dir] + list(passthrough)
            print("\n" + "#" * 78)
            print(f"### {name}: {' '.join(cmd)}")
            print("#" * 78, flush=True)
            proc = subprocess.run(cmd, cwd=repo_root)
            if proc.returncode != 0:
                print(f"\n[run_all] {name} FAILED with exit code {proc.returncode}.", flush=True)
                return proc.returncode

    # -------------------------------------------------------------- aggregate
    results: Dict[str, dict] = {}
    for name in names:
        path = os.path.join(args.out_dir, name, "metrics.json")
        if os.path.exists(path):
            results[name] = load_json(path)
        else:
            print(f"[run_all] missing {path}; skipping in the summary", flush=True)
    if not results:
        print("[run_all] nothing to aggregate")
        return 1

    save_json(results, os.path.join(args.out_dir, "all_results.json"))

    quality_cols = [k for k, _ in MAIN_METRICS]
    quality_hdr = [h for _, h in MAIN_METRICS]
    eff_cols = [k for k, _ in EFFICIENCY_METRICS]
    eff_hdr = [h for _, h in EFFICIENCY_METRICS]

    lines: List[str] = []
    lines.append("# Ablation summary (auto-generated by `src/run_all.py`)\n")
    lines.append("## Configuration matrix\n")
    lines.append("| Config | Changed from base | Positional | Attention | Norm | Tokenization |")
    lines.append("|---|---|---|---|---|---|")
    for n in sorted(results):
        r = results[n]
        lines.append(
            f"| {n} | {r.get('changed','')} | {r.get('pos_encoding','')} | "
            f"{r.get('attention','')} | {r.get('norm','')} | {r.get('tokenization','')} |"
        )

    lines.append("\n## Quality (greedy decoding on the test split)\n")
    lines.append(results_markdown_table(results, quality_cols, quality_hdr))
    lines.append(
        "\n_BLEU/ROUGE are defined by the brief for tokenised models (C1-C4); "
        "the C5 values are byte-level and included for reference only._\n"
    )

    lines.append("\n## Teacher-forced test loss\n")
    lines.append(
        results_markdown_table(
            results,
            ["test_loss", "test_ppl", "test_token_accuracy", "best_val_loss", "best_epoch"],
            ["Test loss", "Test PPL", "Token Acc (%)", "Best val loss", "Best epoch"],
        )
    )

    lines.append("\n## Computational cost\n")
    lines.append(results_markdown_table(results, eff_cols, eff_hdr))

    if "C1" in results:
        lines.append("\n## Delta vs. the C1 baseline\n")
        base = results["C1"]
        delta_cols = ["bit_accuracy", "sequence_accuracy", "levenshtein",
                      "sec_per_epoch", "peak_gpu_mem_mb", "params_millions"]
        lines.append("| Config | " + " | ".join(delta_cols) + " |")
        lines.append("|" + "---|" * (len(delta_cols) + 1))
        for n in sorted(results):
            if n == "C1":
                continue
            row = [n]
            for c in delta_cols:
                a, b = results[n].get(c), base.get(c)
                row.append("n/a" if a is None or b is None else f"{a - b:+.4f}")
            lines.append("| " + " | ".join(row) + " |")

    wandb_rows = [(n, results[n].get("wandb_url", "")) for n in sorted(results)]
    if any(u for _, u in wandb_rows):
        lines.append("\n## WandB runs\n")
        for n, u in wandb_rows:
            lines.append(f"- **{n}**: {u or '(offline)'}")

    md_path = os.path.join(args.out_dir, "report_tables.md")
    with open(md_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    plot_ablation_bars(
        results, quality_cols, os.path.join(args.out_dir, "ablation_quality.png"),
        title="Quality of each configuration (greedy decoding, test split)",
        pretty=dict(MAIN_METRICS),
    )
    plot_efficiency(results, os.path.join(args.out_dir, "ablation_efficiency.png"))

    print("\n" + "=" * 78)
    print("\n".join(lines))
    print("=" * 78)
    print(f"\nWrote {md_path}")
    print(f"Wrote {os.path.join(args.out_dir, 'all_results.json')}")
    print(f"Wrote {os.path.join(args.out_dir, 'ablation_quality.png')}")
    print(f"Wrote {os.path.join(args.out_dir, 'ablation_efficiency.png')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""Parse ANLP_Keys_A1.txt -> .env, then verify W&B / HF / Kaggle logins.

Secrets are never printed: every value is masked as `abcd....wxyz`.

    python setup_keys.py                    # parse ./ANLP_Keys_A1.txt -> ./.env
    python setup_keys.py --keys-file X.txt  # different source file
    python setup_keys.py --verify-only      # just check what's already in .env
"""

from __future__ import annotations

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# Recognised secret shapes -------------------------------------------------- #
RE_HF = re.compile(r"\bhf_[A-Za-z0-9]{20,}\b")
# W&B keys come in two shapes: the legacy 40-char hex key, and the newer
# "wandb_v1_<base64ish>" personal access token.
RE_WANDB_V1 = re.compile(r"\bwandb_v1_[A-Za-z0-9_\-]{20,}\b")
RE_WANDB = re.compile(r"\b[0-9a-f]{40}\b")
RE_KAGGLE_KEY = re.compile(r"\b[0-9a-f]{32}\b")

# key=value / key: value on one line
RE_KV = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_ .\-]*?)\s*[:=]\s*(.+?)\s*$")

# Which .env name each free-text label maps to
LABEL_MAP = {
    "wandb api key": "WANDB_API_KEY",
    "wandb key": "WANDB_API_KEY",
    "wandb apikey": "WANDB_API_KEY",
    "wandb": "WANDB_API_KEY",
    "wandb_api_key": "WANDB_API_KEY",
    "wandb entity": "WANDB_ENTITY",
    "wandb username": "WANDB_ENTITY",
    "wandb user": "WANDB_ENTITY",
    "wandb_entity": "WANDB_ENTITY",
    "wandb project": "WANDB_PROJECT",
    "wandb_project": "WANDB_PROJECT",
    "hugging face": "HF_TOKEN",
    "huggingface": "HF_TOKEN",
    "hugging face token": "HF_TOKEN",
    "huggingface token": "HF_TOKEN",
    "hf token": "HF_TOKEN",
    "hf_token": "HF_TOKEN",
    "hf": "HF_TOKEN",
    "hf api key": "HF_TOKEN",
    "huggingface api key": "HF_TOKEN",
    "hugging face username": "HF_USERNAME",
    "huggingface username": "HF_USERNAME",
    "hf username": "HF_USERNAME",
    "hf_username": "HF_USERNAME",
    "kaggle username": "KAGGLE_USERNAME",
    "kaggle_username": "KAGGLE_USERNAME",
    "kaggle key": "KAGGLE_KEY",
    "kaggle_key": "KAGGLE_KEY",
    "kaggle api key": "KAGGLE_KEY",
    "roll number": "ROLL_NUMBER",
    "rollnumber": "ROLL_NUMBER",
    "roll no": "ROLL_NUMBER",
    "roll_number": "ROLL_NUMBER",
}


def mask(v: str) -> str:
    if not v:
        return "(empty)"
    v = v.strip()
    if len(v) <= 8:
        return v[0] + "*" * (len(v) - 1) if len(v) > 1 else "*"
    return f"{v[:4]}...{v[-4:]}  (len {len(v)})"


def parse_keys_file(path: str) -> dict:
    raw = open(path, encoding="utf-8", errors="replace").read()
    found: dict = {}

    # 1) explicit key: value lines
    for line in raw.splitlines():
        line = line.strip().lstrip("-*#").strip()
        if not line:
            continue
        m = RE_KV.match(line)
        if not m:
            continue
        label, value = m.group(1).strip().lower(), m.group(2).strip()
        value = value.strip("\"'` ")
        if not value or value.lower() in {"none", "n/a", "-"}:
            continue
        # normalise label: collapse whitespace/underscores
        norm = re.sub(r"[\s_]+", " ", label).strip()
        target = LABEL_MAP.get(norm) or LABEL_MAP.get(norm.replace(" ", "_"))
        if target and target not in found:
            found[target] = value

    # 2) shape-based fallback for anything still missing
    if "HF_TOKEN" not in found:
        m = RE_HF.search(raw)
        if m:
            found["HF_TOKEN"] = m.group(0)
    if "WANDB_API_KEY" not in found:
        m = RE_WANDB_V1.search(raw)          # new-style wandb_v1_... token
        if m:
            found["WANDB_API_KEY"] = m.group(0)
    if "WANDB_API_KEY" not in found:
        # legacy: a 40-hex string that is not the HF token
        for m in RE_WANDB.finditer(raw):
            found["WANDB_API_KEY"] = m.group(0)
            break
    if "KAGGLE_KEY" not in found:
        for m in RE_KAGGLE_KEY.finditer(raw):
            found["KAGGLE_KEY"] = m.group(0)
            break
    return found


def read_env(path: str) -> dict:
    out = {}
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def write_env(path: str, values: dict) -> None:
    order = [
        "WANDB_API_KEY", "WANDB_ENTITY", "WANDB_PROJECT",
        "HF_TOKEN", "HF_USERNAME",
        "KAGGLE_USERNAME", "KAGGLE_KEY",
        "ROLL_NUMBER",
    ]
    lines = [
        "# Auto-generated by setup_keys.py -- DO NOT COMMIT OR SHARE THIS FILE.",
        "# Regenerate with:  python setup_keys.py",
        "",
    ]
    for k in order:
        lines.append(f"{k}={values.get(k, '')}")
    extra = sorted(set(values) - set(order))
    if extra:
        lines.append("")
        for k in extra:
            lines.append(f"{k}={values[k]}")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    try:  # best-effort: make it user-readable only
        os.chmod(path, 0o600)
    except Exception:
        pass


def load_env_into_os(path: str) -> dict:
    env = read_env(path)
    for k, v in env.items():
        if v:
            os.environ[k] = v
    return env


# --------------------------------------------------------------------------- #
# verification
# --------------------------------------------------------------------------- #
def verify_wandb() -> str:
    key = os.environ.get("WANDB_API_KEY", "")
    if not key:
        return "SKIP  WANDB_API_KEY not set"
    try:
        import wandb
        ok = wandb.login(key=key, relogin=True, verify=True)
        if not ok:
            return "FAIL  wandb.login returned False"
        api = wandb.Api()
        who = api.viewer
        name = getattr(who, "username", None) or getattr(who, "entity", None) or "?"
        return f"OK    W&B authenticated as '{name}'"
    except Exception as e:
        return f"FAIL  W&B: {type(e).__name__}: {e}"


def verify_hf() -> str:
    tok = os.environ.get("HF_TOKEN", "")
    if not tok:
        return "SKIP  HF_TOKEN not set"
    try:
        from huggingface_hub import HfApi
        api = HfApi(token=tok)
        info = api.whoami()
        name = info.get("name", "?")
        perm = (info.get("auth", {}).get("accessToken", {}) or {}).get("role", "?")
        os.environ.setdefault("HF_USERNAME", name)
        return f"OK    HF authenticated as '{name}' (token role: {perm})"
    except Exception as e:
        return f"FAIL  HF: {type(e).__name__}: {e}"


def verify_kaggle() -> str:
    u, k = os.environ.get("KAGGLE_USERNAME", ""), os.environ.get("KAGGLE_KEY", "")
    if not (u and k):
        return "SKIP  KAGGLE_USERNAME / KAGGLE_KEY not set (Kaggle upload is optional)"
    try:
        from kaggle.api.kaggle_api_extended import KaggleApi
        api = KaggleApi()
        api.authenticate()
        return f"OK    Kaggle authenticated as '{u}'"
    except Exception as e:
        return f"FAIL  Kaggle: {type(e).__name__}: {e}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--keys-file", default=os.path.join(HERE, "ANLP_Keys_A1.txt"))
    ap.add_argument("--env-file", default=os.path.join(HERE, ".env"))
    ap.add_argument("--verify-only", action="store_true")
    ap.add_argument("--no-verify", action="store_true")
    a = ap.parse_args()

    values = read_env(a.env_file)

    if not a.verify_only:
        if not os.path.exists(a.keys_file):
            print(f"[keys] no key file at {a.keys_file}; using existing .env only")
        else:
            parsed = parse_keys_file(a.keys_file)
            print(f"[keys] parsed {len(parsed)} value(s) from {os.path.basename(a.keys_file)}")
            for k, v in parsed.items():
                values.setdefault(k, v) if values.get(k) else values.update({k: v})
        values.setdefault("WANDB_PROJECT", "anlp-a1-blt-ablation")
        write_env(a.env_file, values)
        print(f"[keys] wrote {a.env_file}")

    load_env_into_os(a.env_file)

    print("\n--- resolved (masked) ---")
    for k in ["WANDB_API_KEY", "WANDB_ENTITY", "WANDB_PROJECT", "HF_TOKEN",
              "HF_USERNAME", "KAGGLE_USERNAME", "KAGGLE_KEY", "ROLL_NUMBER"]:
        v = os.environ.get(k, "")
        secret = k in {"WANDB_API_KEY", "HF_TOKEN", "KAGGLE_KEY"}
        print(f"  {k:18s} = {mask(v) if secret else (v or '(empty)')}")

    if a.no_verify:
        return 0

    print("\n--- verification ---")
    for line in (verify_wandb(), verify_hf(), verify_kaggle()):
        print("  " + line)

    # persist anything verification discovered (e.g. HF_USERNAME)
    for k in ("HF_USERNAME",):
        if os.environ.get(k) and not values.get(k):
            values[k] = os.environ[k]
    if not a.verify_only:
        write_env(a.env_file, values)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""Generate the LaTeX result tables for Report.tex from outputs/all_results.json.

    python report/make_tables.py

Writes two files:
  * ``results_tables.tex``  -- one merged quality+cost table (body only)
  * ``results_macros.tex``  -- \\newcommand definitions only (preamble-safe)

A single merged table is emitted rather than several sparse ones, to stay inside
the six-page limit. Regenerate after re-training and the report updates itself.
"""

from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ORDER = ["C1", "C2", "C3", "C4", "C5"]

# LaTeX control sequences may not contain digits: C1 -> \CfgOneBit, etc.
WORD = {"C1": "One", "C2": "Two", "C3": "Three", "C4": "Four", "C5": "Five"}


def f(v, nd=2, dash="--"):
    if v is None:
        return dash
    try:
        return f"{float(v):.{nd}f}"
    except (TypeError, ValueError):
        return str(v)


def ratio(a, b, nd=2):
    if a is None or b is None or not float(b):
        return "--"
    return f"{float(a)/float(b):.{nd}f}"


def is_best(vals, idx, lower=False):
    nums = [v for v in vals if isinstance(v, (int, float))]
    if not nums or not isinstance(vals[idx], (int, float)):
        return False
    return vals[idx] == (min(nums) if lower else max(nums))


def main() -> int:
    path = os.path.join(ROOT, "outputs", "all_results.json")
    if not os.path.exists(path):
        print(f"[tables] {path} not found - train first (python run_ablation.py)")
        return 1
    R = json.load(open(path, encoding="utf-8"))
    names = [n for n in ORDER if n in R]
    if not names:
        print("[tables] no configs found")
        return 1
    base = R.get("C1", {})

    L: list[str] = []
    A = L.append
    A("% Auto-generated by report/make_tables.py -- do not edit by hand.")
    A("")

    # ------------------------------------------ merged quality + cost table
    QK = ("bit_accuracy", "sequence_accuracy", "levenshtein", "bleu", "rougeL")
    cols = {k: [R[n].get(k) for n in names] for k in QK}

    def cell(key, i, nd=2, lower=False):
        s = f(cols[key][i], nd)
        return r"\textbf{" + s + "}" if is_best(cols[key], i, lower) else s

    A(r"\begin{table*}[t]")
    A(r"\centering\small")
    A(r"\setlength{\tabcolsep}{5pt}")
    A(r"\begin{tabular}{lrrrrrcrrrr}")
    A(r"\toprule")
    A(r"& \multicolumn{5}{c}{\textbf{Quality (greedy decoding)}} & "
      r"& \multicolumn{4}{c}{\textbf{Cost}} \\")
    A(r"\cmidrule(lr){2-6}\cmidrule(lr){8-11}")
    A(r"\textbf{Cfg} & \textbf{Bit \%} & \textbf{Seq \%} & "
      r"\textbf{Lev.} & \textbf{BLEU} & \textbf{R-L} & & "
      r"\textbf{Par (M)} & \textbf{s/ep} & \textbf{Peak MB} & \textbf{Dec (s)} \\")
    A(r"\midrule")
    for i, n in enumerate(names):
        r = R[n]
        A(f"{n} & {cell('bit_accuracy', i)} & {cell('sequence_accuracy', i)} & "
          f"{cell('levenshtein', i, 2, True)} & {cell('bleu', i)} & "
          f"{cell('rougeL', i)} & & "
          f"{f(r.get('params_millions'))} & {f(r.get('sec_per_epoch'), 1)} & "
          f"{f(r.get('peak_gpu_mem_mb'), 0)} & "
          f"{f(r.get('generation_seconds'), 1)} \\\\")
    A(r"\bottomrule")
    A(r"\end{tabular}")
    A(r"\caption{Test-set results (25 epochs each); best per column in "
      r"\textbf{bold}. Levenshtein is mean edit distance per segment, lower is "
      r"better. Cost measured on one RTX 3050 Laptop GPU (4\,GB, bfloat16), each "
      r"configuration in its own process; `Dec.'\ decodes 1{,}000 segments.}")
    A(r"\label{tab:quality}")
    A(r"\end{table*}")
    A("")

    # ------------------------------------------------------------- macros
    M: list[str] = []
    A2 = M.append
    A2("% Auto-generated by report/make_tables.py -- do not edit by hand.")
    A2(r"% Inline single-number macros, e.g. \CfgOneBit, \CfgFiveMem.")
    for n in names:
        r = R[n]
        for key, macro, nd in [
            ("bit_accuracy", "Bit", 2), ("sequence_accuracy", "Seq", 2),
            ("levenshtein", "Lev", 2), ("params_millions", "Par", 2),
            ("sec_per_epoch", "Sec", 1), ("peak_gpu_mem_mb", "Mem", 0),
            ("test_ppl", "Ppl", 2), ("generation_seconds", "Gen", 1),
            ("test_token_accuracy", "Tok", 2), ("best_epoch", "Ep", 0),
            ("test_loss", "Loss", 4), ("bleu", "Bleu", 2),
            ("rougeL", "Rouge", 2), ("epochs_run", "Epochs", 0),
        ]:
            A2(f"\\newcommand{{\\Cfg{WORD[n]}{macro}}}{{{f(r.get(key), nd)}}}")

    if base.get("peak_gpu_mem_mb") and R.get("C5", {}).get("peak_gpu_mem_mb"):
        A2(f"\\newcommand{{\\BltMemRatio}}"
           f"{{{ratio(R['C5']['peak_gpu_mem_mb'], base['peak_gpu_mem_mb'])}}}")
    if base.get("sec_per_epoch") and R.get("C5", {}).get("sec_per_epoch"):
        A2(f"\\newcommand{{\\BltTimeRatio}}"
           f"{{{ratio(R['C5']['sec_per_epoch'], base['sec_per_epoch'])}}}")
    if base.get("generation_seconds") and R.get("C5", {}).get("generation_seconds"):
        A2(f"\\newcommand{{\\BltDecodeRatio}}"
           f"{{{ratio(R['C5']['generation_seconds'], base['generation_seconds'])}}}")

    # Guard: a macro referenced by the prose but absent (config not trained)
    # would be an "Undefined control sequence" crash. Define those as "--".
    A2("")
    A2("% fallbacks for configs that were not trained")
    for n in ORDER:
        if n in names:
            continue
        for macro in ["Bit", "Seq", "Lev", "Par", "Sec", "Mem", "Ppl", "Gen",
                      "Tok", "Ep", "Loss", "Bleu", "Rouge", "Epochs"]:
            A2(f"\\providecommand{{\\Cfg{WORD[n]}{macro}}}{{--}}")
    A2(r"\providecommand{\BltMemRatio}{--}")
    A2(r"\providecommand{\BltTimeRatio}{--}")
    A2(r"\providecommand{\BltDecodeRatio}{--}")

    out = os.path.join(HERE, "results_tables.tex")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    mout = os.path.join(HERE, "results_macros.tex")
    with open(mout, "w", encoding="utf-8") as fh:
        fh.write("\n".join(M) + "\n")
    print(f"[tables] wrote {out}")
    print(f"[tables] wrote {mout}  for: {', '.join(names)}")

    print("\n  cfg   bit%    seq%    lev     bleu    params  s/ep    peakMB  dec")
    for n in names:
        r = R[n]
        print(f"  {n:<5} {f(r.get('bit_accuracy')):<7} "
              f"{f(r.get('sequence_accuracy')):<7} {f(r.get('levenshtein')):<7} "
              f"{f(r.get('bleu')):<7} {f(r.get('params_millions')):<7} "
              f"{f(r.get('sec_per_epoch'), 1):<7} "
              f"{f(r.get('peak_gpu_mem_mb'), 0):<7} "
              f"{f(r.get('generation_seconds'), 1)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
